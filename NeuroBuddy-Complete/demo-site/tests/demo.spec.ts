import { expect, test } from '@playwright/test'

test.describe('Neurobuddy demo', () => {
  test('hero CTAs, sample banner, and walkthrough modal', async ({ page }) => {
    await page.goto('/')
    await expect(page.getByRole('status')).toContainText(/illustrative sample data/i)
    await expect(page.getByRole('heading', { name: 'Neurobuddy' })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Scene' }).getByRole('link')).toHaveCount(7)
    await expect(page.getByRole('navigation', { name: 'Scene' }).getByRole('link', { name: 'Hero' })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Scene' }).getByRole('link', { name: 'Close' })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Scene' }).getByRole('link', { name: /^0[1-7]$/ })).toHaveCount(0)
    await expect(page.locator('body')).not.toContainText(/Scene 0[1-7]/)
    await expect(page.locator('a[href="#openneuro"]')).toHaveCount(0)
    await expect(page.locator('#openneuro')).toHaveCount(0)
    await page.getByRole('button', { name: 'Watch product walkthrough' }).click()
    await expect(page.getByRole('dialog', { name: /walkthrough/i })).toBeVisible()
    await page.getByRole('button', { name: 'Close walkthrough' }).click()
    await expect(page.getByRole('dialog', { name: /walkthrough/i })).toHaveCount(0)
    const heroImplement = page.locator('#hero').getByRole('link', { name: /Implement Neurobuddy/ })
    await expect(heroImplement).toHaveAttribute('href', 'https://www.athleticperformanceintelligence.com/')
    await expect(heroImplement).toHaveAttribute('target', '_blank')
    await expect(heroImplement).toHaveAttribute('rel', /noopener/)
    await page.getByRole('link', { name: 'Explore the interactive demo' }).click()
    await expect(page.locator('#pipeline')).toBeInViewport()
    await expect(page.locator('#pipeline img[src="/media/pipeline-eeg-woman.jpg"]')).toBeVisible()
    await expect(page.locator('#pipeline img[src="/media/api-wordmark.png"]')).toBeVisible()
  })

  test('library explains folders and offers a walkthrough video', async ({ page }) => {
    await page.goto('/#library')
    await expect(page.getByRole('heading', { name: 'Team, athlete, shelf.' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Make a team folder' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Make an athlete folder' })).toBeVisible()
    await expect(page.locator('#library').getByText('Atlas Sprint Lab', { exact: true })).toBeVisible()
    const video = page.locator('#library video')
    await expect(video).toBeVisible()
    await expect(video).toHaveAttribute('src', '/media/all-tests.mp4')
    await expect(video).toHaveAttribute('controls', '')
    await expect(video).not.toHaveAttribute('autoplay')
    await expect(page.getByRole('button', { name: '+ Team' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Send to processing' })).toHaveCount(0)
  })

  test('experiment selector updates slots', async ({ page }) => {
    await page.goto('/#tasks')
    await expect(page.locator('#tasks').getByRole('heading', { name: 'Oddball' })).toBeVisible()
    await page.getByRole('listbox', { name: 'Experiment selector' }).getByRole('option', { name: 'Sleep' }).click()
    await expect(page.locator('#tasks').getByRole('heading', { name: 'Sleep' })).toBeVisible()
    await expect(page.getByText(/Automatically staged results are unreviewed/i)).toBeVisible()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('heading', { name: 'Unspecified' })).toBeVisible()
  })

  test('HTML report carousel', async ({ page }) => {
    await page.goto('/#reports')
    await expect(page.getByRole('heading', { name: 'What each HTML report actually contains.' })).toBeVisible()
    await expect(page.getByRole('listbox', { name: 'HTML report type' })).toBeVisible()
    await page.getByRole('listbox', { name: 'HTML report type' }).getByRole('option', { name: 'Sleep' }).click()
    await expect(page.locator('#reports').getByRole('heading', { name: 'Sleep' })).toBeVisible()
    await expect(page.getByText(/Estimated stages are research screening/i)).toBeVisible()
    await page.keyboard.press('ArrowRight')
    await expect(page.locator('#reports').getByRole('heading', { name: 'Motor imagery' })).toBeVisible()
    await expect(page.getByText(/does not measure exertion or recovery/i)).toBeVisible()
  })

  test('packages revolving menu shows Analysis still and package video', async ({ page }) => {
    await page.goto('/#advanced')
    await expect(page.getByRole('heading', { name: 'Reports, then packages.' })).toBeVisible()
    await expect(page.getByRole('listbox', { name: 'Package views' })).toBeVisible()
    await expect(page.locator('#advanced img[src="/media/Screenshot_Analysis.png"]')).toBeVisible()
    await page.getByRole('listbox', { name: 'Package views' }).getByRole('option', { name: 'Packages' }).click()
    const video = page.locator('#advanced video')
    await expect(video).toBeVisible()
    await expect(video).toHaveAttribute('src', '/media/package-drag.mp4')
    await expect(video).toHaveAttribute('controls', '')
    await expect(video).not.toHaveAttribute('autoplay')
    await expect(page.locator('#advanced')).not.toContainText(/oracle|not connected|unimplemented|AI interpretation/i)
  })

  test('replay CTA restores the hero', async ({ page }) => {
    await page.goto('/#close')
    await expect(page.locator('#close img[src="/media/api-wordmark.png"]')).toBeVisible()
    await expect(page.getByRole('listbox', { name: 'Coaching struggles' })).toBeVisible()
    await expect(page.getByRole('listbox', { name: 'Coaching struggles' }).getByRole('option', { name: 'No Complete View of the Athlete' })).toBeVisible()
    await expect(page.getByRole('listbox', { name: 'Coaching struggles' }).getByRole('option', { name: /^0[1-5]$/ })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'No Complete View of the Athlete' })).toBeVisible()
    await page.getByRole('listbox', { name: 'Coaching struggles' }).getByRole('option', { name: 'Limited Decision Support' }).click()
    await expect(page.getByText(/incomplete or disconnected information/)).toBeVisible()
    await page.getByRole('listbox', { name: 'Coaching struggles' }).getByRole('option', { name: 'How Neurobuddy gathers neural analysis' }).click()
    await expect(page.locator('#close').getByText(/not a diagnosis/)).toBeVisible()
    await expect(page.locator('#close')).not.toContainText(/not connected|unimplemented|oracle/i)
    await expect(page.locator('#close').getByRole('button', { name: 'Replay the demo' })).toHaveCount(0)
    await expect(page.locator('#close').getByRole('button', { name: 'Watch walkthrough' })).toHaveCount(0)
    await expect(page.locator('#capabilities')).toHaveCount(0)
    await expect(page.locator('#close')).not.toContainText(/JSON \/ CSV|View all capabilities|Team \/ athlete \/ shelf library/)
    await expect(page.locator('#close form')).toHaveCount(0)
    const implement = page.locator('#close').getByRole('link', { name: /Implement Neurobuddy/ })
    await expect(implement).toBeVisible()
    await expect(implement).toHaveAttribute('href', 'https://www.athleticperformanceintelligence.com/')
    await expect(implement).toHaveAttribute('target', '_blank')
    await expect(implement).toHaveAttribute('rel', /noopener/)
  })

  test('reduced motion does not keep the axon pulse running', async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    await expect(page.locator('html')).toHaveAttribute('data-motion', 'reduced')
  })
})
